export function getStoredLang(): Lang {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    if (v === 'hi' || v === 'mr' || v === 'bn' || v === 'ta' || v === 'te' || v === 'kn' || v === 'gu' || v === 'ur' || v === 'pa' || v === 'or') return v as Lang;
  } catch (e) {}
  return 'en';
}

export function setStoredLang(lang: Lang) {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch (e) {}
}

export function t(key: string, lang: Lang = getStoredLang()): string {
  const entry = TRANSLATIONS[key];
  if (!entry) return key;
  return entry[lang] || entry['en'] || key;
}

// translate DOM elements with data-i18n and data-i18n-placeholder
export function translateDOM(lang: Lang) {
  try {
    setStoredLang(lang);
    const els = document.querySelectorAll('[data-i18n]');
    els.forEach((el) => {
      const k = el.getAttribute('data-i18n') || '';
      if (!k) return;
      const txt = t(k, lang);
      if (el instanceof HTMLInputElement || el instanceof HTMLTextAreaElement) {
        if (el.placeholder !== undefined) el.placeholder = txt;
      } else {
        el.textContent = txt;
      }
    });

    const placeholders = document.querySelectorAll('[data-i18n-placeholder]');
    placeholders.forEach((el) => {
      const k = el.getAttribute('data-i18n-placeholder') || '';
      if (!k) return;
      const txt = t(k, lang);
      if (el instanceof HTMLInputElement || el instanceof HTMLTextAreaElement) {
        el.placeholder = txt;
      }
    });

    // emit event
    try { window.dispatchEvent(new CustomEvent('lang.change', { detail: { lang } })); } catch (e) {}
  } catch (e) {
    // ignore
  }
}

